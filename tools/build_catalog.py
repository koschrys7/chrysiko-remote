#!/usr/bin/env python3
"""Compact the editor's algorithm catalogue (v1.0.7_alg_data.json) into catalog.js for the page.
Keeps only category index, module, model code/name and parameter names/IDs/ranges/widget type
(0 knob, 2 choice, 3 switch, 4 slider) and step (default 1)."""
import json
from pathlib import Path
HERE = Path(__file__).resolve().parents[1]; LAB = HERE.parents[1]
SRC = LAB / "vendor-software/hotone-setup-1.3.1/pkg-expanded/Ampero_II.pkg/Payload/Ampero II.app/Contents/Frameworks/App.framework/Versions/A/Resources/flutter_assets/assets/data/v1.0.7_alg_data.json"
cat = {}
for m in json.loads(SRC.read_text())["PluginProperties"]["Modules"]["Catalog"]:
    algs = {}
    for a in m["Alg"]:
        ws = a.get("Widget") or []
        ws = [ws] if isinstance(ws, dict) else ws  # a one-knob model stores a single object
        algs[int(a["Code"])] = [a["Name"], [[w["Name"], int(w["ID"]), float(w["DisplayMin"]), float(w["DisplayMax"]), int(w.get("Type", 0)), float(w.get("Step", 1))] for w in ws]]
    cat[int(m["Index"])] = {"module": m["Name"], "algs": algs}
(HERE / "catalog.js").write_text("// Generated by tools/build_catalog.py from the editor catalogue v1.0.7. Do not edit.\nexport const CATALOG = " + json.dumps(cat, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(sum(len(v["algs"]) for v in cat.values()), "models in", len(cat), "categories")
